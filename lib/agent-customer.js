function buildTools(kb, psid) {
  return {
    async save_lead(input) {
      const level = findLevel(kb, input.level_id);
      const lead = await upsertLead(psid, {
        name: input.name,
        phone: input.phone,
        levelId: level?.id ?? input.level_id ?? null,
        levelName: level?.name ?? null,
        preferredStart: input.preferred_start ?? null,
        preferredTime: input.preferred_time ?? null,
        note: input.note ?? null,
        source: "messenger",
      });

      // Хоосон талбарыг огт оруулахгүй — "—" зураасууд нүд элээнэ.
      await notifyAdmins(
        [
          "🟢 Шинэ хүн бүртгүүллээ!",
          "",
          `${lead.name} — ${lead.phone}`,
          lead.levelName ?? lead.levelId ?? null,
          lead.preferredStart ? `Хэзээ эхлэх: ${lead.preferredStart}` : null,
          lead.preferredTime ? `Тохирох цаг: ${lead.preferredTime}` : null,
          lead.note ? `Тэмдэглэл: ${lead.note}` : null,
        ]
          .filter((line) => line !== null)
          .join("\n"),
      );

      return "Бүртгэл амжилттай хадгалагдаж, ажилтанд мэдэгдлээ.";
    },

    async report_unknown(input) {
      const record = await addUnknown({
        psid,
        question: input.question,
        context: input.context ?? null,
      });

      // PSID-г эндээс хассан — хүнд хэрэггүй. Хэрэгтэй бол админ AI
      // list_unknowns-оор олж авна.
      await notifyAdmins(
        [
          "❓ Нэг хүн ийм юм асуулаа, би мэдэхгүй байлаа:",
          "",
          `"${record.question}"`,
          record.context ? `(${record.context})` : null,
          "",
          `Хариуг нь надад бичээд өгвөл санд нь оруулчихна. Асуулт #${record.id}`,
        ]
          .filter((line) => line !== null)
          .join("\n"),
      );

      return `Асуулт #${record.id} дугаараар админд бүртгэгдлээ. Одоо хэрэглэгчид мэдэхгүй байгаагаа үнэнээр хэлж, лавлаад эргэж хариулна гэж мэдэгд.`;
    },
  };
}

const FALLBACK_REPLY =
  "Уучлаарай, техникийн түр зуурын алдаа гарлаа. Түр хүлээгээд дахин бичнэ үү 🙏";

/**
 * Messenger-ээс ирсэн нэг мессежийг боловсруулж, хариу текстийг буцаана.
 */
export async function handleCustomerMessage({ psid, text, profileName }) {
  const kb = await loadKb();
  const history = await getHistory(psid);

  const systemBlocks = [
    {
      type: "text",
      text: `${RULES}\n\n<мэдээллийн_сан>\n${renderKb(kb)}\n</мэдээллийн_сан>`,
      cache_control: { type: "ephemeral" },
    },
    {
      type: "text",
      text: [
        `Өнөөдрийн огноо: ${todayInUB()} (Улаанбаатарын цагаар).`,
        profileName
          ? `Facebook дээрх энэ хэрэглэгчийн нэр: ${profileName}. Бүртгэлд ` +
            `оруулахдаа өөрөөс нь нэрээ баталгаажуулж асуу — Facebook нэр ` +
            `нь жинхэнэ нэр биш байж болно.`
          : null,
      ]
        .filter(Boolean)
        .join("\n"),
    },
  ];

  const messages = [...history, { role: "user", content: text }];

  const result = await runAgent({
    systemBlocks,
    messages,
    tools: TOOLS,
    toolHandlers: buildTools(kb, psid),
    model: env.customerModel, // админ AI-аас тусдаа — ANTHROPIC_MODEL_CUSTOMER
    effort: "low",
    maxTokens: 8000,
  });

  const reply = result.text.trim();
  if (!reply) return { reply: FALLBACK_REPLY, saved: false };

  await saveHistory(psid, result.messages);
  return { reply, saved: true };
}
